export type TranslationKey = keyof typeof nl;


/**
 * De tabellen die nu geladen zijn.
 *
 * Nederlands zit er altijd in: dat is de bron en het startpunt, ook op de
 * server. Engels komt erbij zodra iemand die taal kiest -- zie `loadTable`.
 */
const TABLES: Partial<Record<Language, Record<TranslationKey, string>>> = { nl };

/** Meldt een geladen tabel aan. */
export function registerTable(
  language: Language,
  table: Record<TranslationKey, string>,
): void {
  TABLES[language] = table;
}

/**
 * Haalt de tabel van een taal op als die er nog niet is.
 *
 * Nederlands is er altijd, dus daar gebeurt niets. Voor Engels wordt het losse
 * bestand opgehaald; lukt dat niet (geen bereik op precies dat moment), dan
 * blijft de app in het Nederlands staan in plaats van stuk te gaan.
 */
export async function loadTable(language: Language): Promise<void> {
  if (TABLES[language]) return;
  try {
    const { en } = await import("./dictionary.en");
    registerTable("en", en);
  } catch {
    // Dan leest hij Nederlands; dat is beter dan een leeg scherm.
  }
}

/** Vult {plekken} in met de meegegeven waarden. */
function fill(template: string, values?: Values): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

export function translate(language: Language, key: TranslationKey, values?: Values): string {
  // Is de tabel er nog niet, dan het Nederlands: een zin in de verkeerde taal
  // is beter dan een sleutel op het scherm.
  const table = TABLES[language] ?? nl;
  return fill(table[key] ?? nl[key] ?? key, values);
}
